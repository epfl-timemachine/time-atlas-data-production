"""
produce_cloudpoint_data_v2.py

Rewrite of produce_cloudpoint_data.py using the timeatlas library classes
directly for RDE objects.

The UUID seeds mirror the legacy script:
- Dataset: DATASET_CONFIGURATION.slug
- HistoricalRecord: CSV serialization of EDIFI_ID
- Observation: CSV serialization of geometry plus "obs"
- IIIF manifests and collections: same namespace and string seeds as v1

The dataset references building geometries generated by the Cini photographs
pipeline, so this script does not materialize Geometry objects locally.
"""

import json
import os
import re
import sys

import geopandas as gpd
import pandas as pd
from tqdm import tqdm

# Library bootstrap
parent_dir = os.path.abspath("../../../")
if parent_dir not in sys.path:
    sys.path.insert(0, parent_dir)
timeatlas_dir = os.path.join(parent_dir, "time-atlas-python")
if timeatlas_dir not in sys.path:
    sys.path.insert(0, timeatlas_dir)

from timeatlas.DocumentModel import Annotation, Collection, Document, Model, Page
from timeatlas.RDEModel import (
    Dataset,
    Geometry,
    HistoricalRecord,
    MultiLingualValue,
    Observation,
    RDETimeRange,
    UUIDManager,
)
from timeatlas.TimeAtlas import RDECollection
from timeatlas.production import datetime_from_int, normalize_to_epsg4326, csv_seed


IIIF_BASE_URL = "https://image-timemachine.epfl.ch/iiif/3"


with open("dataproduction_config_edifici.json", encoding="utf-8") as f:
    DATA_CONFIG = json.load(f)

uuid_mgr = UUIDManager(DATA_CONFIG["UUID_NAMESPACE"])
DS_SLUG = DATA_CONFIG["DATASET_CONFIGURATION"]["slug"]
DS_UUID = uuid_mgr._generate_uuid(DS_SLUG)

TR_START = datetime_from_int(DATA_CONFIG["TIMERANGE_MINIMUM"])
TR_END = datetime_from_int(DATA_CONFIG["TIMERANGE_MAXIMUM"], match_to_end=True)
TIME_RANGE = RDETimeRange(TR_START, TR_END)

MAP_FOLDER = "../../maps/venice-2024-contemporary/"


def extract_uid_square_bracket(value: str) -> str | None:
    match = re.search(r"\[uid_(W?\d+)\]", value)
    return match.group(1) if match else None


def extract_uid_beginning(value: str) -> str | None:
    match = re.search(r"(\d+)", value)
    return match.group(1) if match else None


# 1. Load and prepare source data
df = (
    gpd.read_file("src/2025-08-06_edifici_forwebinterface.geojson")
    .pipe(normalize_to_epsg4326)
    .explode()
    .drop_duplicates()
)
df["EDIFI_ID"] = df["EDIFI_ID"].astype(str)
df = df[~df["EDIFI_ID"].isin(["6422", "6421"])]
df["start_time"] = TR_START
df["end_time"] = TR_END

with open("../venice-cini-photographs/edifici_id_to_geom_uuid.json", encoding="utf-8") as f:
    edifici_id_to_geom_uuid = json.load(f)

df["geometry_uuid"] = df["EDIFI_ID"].map(edifici_id_to_geom_uuid)
df["has_geometry"] = df["geometry_uuid"].apply(lambda value: [value])
df["aulic_name"] = df["aulic_name"].fillna("Unknown edifice name")
df["centroid"] = df["geometry"].apply(lambda geometry: geometry.centroid)

df["hr_uuid"] = df.apply(lambda row: uuid_mgr._generate_uuid(csv_seed(row, ["EDIFI_ID"])), axis=1)
df["obs_uuid"] = df.apply(lambda row: uuid_mgr._generate_uuid(csv_seed(row, ["geometry"], "obs")), axis=1)


# 2. Observations
observations = Observation.observations_from_df(
    df,
    id_col="obs_uuid",
    hr_col="hr_uuid",
    geometry_col="centroid",
    has_geometries_col="has_geometry",
)


# 3. Historical Records
cols_of_non_interest = [
    "geometry",
    "centroid",
    "hr_uuid",
    "obs_uuid",
    "has_geometry",
    "geometry_uuid",
    "start_date",
    "end_date",
    "SESTIERE_ABR",
    "end_time",
    "start_time",
    "type",
]

df["type"] = "3d-structure"
metadata_columns = [column for column in df.columns if column not in cols_of_non_interest]
historical_records = HistoricalRecord.historical_records_from_df(
    df,
    id_col="hr_uuid",
    obs_col="obs_uuid",
    dataset_id=DS_UUID,
    time_range=TIME_RANGE,
    metadata_cols=metadata_columns,
)

hr_records = [hr.to_dict() for hr in historical_records]
df_of_hr = pd.DataFrame(data=hr_records)
df_of_hr["EDIFI_ID"] = df_of_hr["metadata"].apply(lambda value: str(value["EDIFI_ID"]).zfill(4) if "EDIFI_ID" in value else None)
df_of_hr["label_txt"] = df_of_hr["metadata"].apply(lambda value: f"{value['aulic_name']}, {value['EDIFI_ID']} - {value['CIVICI']}")


# 4. IIIF manifests for extracted 2D figures
df_img = pd.read_csv("src/2025-08-25_images_width_height.csv")
extract_strategy_per_folder = {
    "edifici_depthmap": extract_uid_beginning,
    "edifici_facades": extract_uid_square_bracket,
    "edifici_panoramas": extract_uid_beginning,
    "street_depthmap_noaxis": extract_uid_beginning,
    "street_depthmap_waxis": extract_uid_square_bracket,
    "street_panopticon_noaxis": extract_uid_square_bracket,
    "street_panopticon_waxis": extract_uid_square_bracket,
}
df_img["uid"] = df_img.apply(lambda row: extract_strategy_per_folder[row["folder"]](row["filename"]), axis=1)
df_img["uid"] = df_img["uid"].apply(lambda value: value.replace("W", "0"))
df_img["uid"] = df_img["uid"].apply(lambda value: value.zfill(4) if len(value) < 4 else value)

edificies_order = [
    "edifici_panoramas",
    "edifici_depthmap",
    "edifici_footprints",
    "edifici_facades",
]
streets_order = [
    "street_panopticon_noaxis",
    "street_panopticon_waxis",
    "street_depthmap_noaxis",
    "street_depthmap_waxis",
    "street_facades",
]


def sorting_key(folder: str) -> int:
    if folder in edificies_order:
        return edificies_order.index(folder)
    if folder in streets_order:
        return streets_order.index(folder)
    return len(edificies_order) + len(streets_order)


def sort_group(dataframe: pd.DataFrame, group_key: tuple[str, str]) -> pd.DataFrame:
    sorted_df = dataframe.sort_values("folder", key=lambda values: values.map(sorting_key))
    sorted_df["uid"] = group_key[0]
    sorted_df["type"] = group_key[1]
    return sorted_df


df_img["type"] = df_img["folder"].apply(lambda value: "edifici" if "edifici" in value else "street")
df_man = df_img.groupby(["uid", "type"]).apply(lambda value: sort_group(value, value.name))
df_man_edifici = df_man[df_man["type"] == "edifici"].drop(columns=["uid"])

os.makedirs("iiif/manifests", exist_ok=True)
os.makedirs("iiif/collections", exist_ok=True)

documents_2d: dict[str, Document] = {}
for group, sdf in tqdm(df_man_edifici.groupby("uid"), desc="2D IIIF manifests"):
    vals = df_of_hr[df_of_hr["EDIFI_ID"] == group]
    if len(vals) == 0:
        print(f"Warning: no HR found for group {group}, skipping")
        continue

    manifest_label = vals["label_txt"].iloc[0]
    hr_uuid = vals["id"].iloc[0]
    manifest_uuid = uuid_mgr._generate_uuid(manifest_label)
    pages = [
        Page(
            id=uuid_mgr._generate_uuid(f"{DS_UUID}_{manifest_uuid}_0"),
            label=MultiLingualValue({"en": ["Thumbnail of the cloudpoint model"]}),
            format="image/png",
            range_idx=0,
            height=512,
            width=1024,
            object_ref=f"venice/3Dbuilding/thumbnails/edifici_{int(group)}.png",
            annotations=[
                Annotation(
                    id=uuid_mgr._generate_uuid(f"annotation_{manifest_uuid}_{hr_uuid}"),
                    lang="en",
                    value=manifest_label,
                    hr_id=hr_uuid,
                )
            ],
        )
    ]

    for index, (_, row) in enumerate(sdf.iterrows(), start=1):
        pages.append(
            Page(
                id=uuid_mgr._generate_uuid(f"{DS_UUID}_{manifest_uuid}_{index}"),
                label=MultiLingualValue({"en": [row["filename"].replace("/", "").replace(".png", "")]}),
                format=row["media_type"],
                range_idx=index,
                height=int(row["height"]),
                width=int(row["width"]),
                object_ref="venice/3Dbuilding/figures/"
                + row["folder"].replace("/", "")
                + "/"
                + row["filename"].replace("/", ""),
            )
        )

    document = Document(
        id=manifest_uuid,
        label=MultiLingualValue({"en": [manifest_label]}),
        items=pages,
    )
    documents_2d[manifest_uuid] = document
    with open(f"iiif/manifests/{manifest_uuid}.json", "w", encoding="utf-8") as f:
        json.dump(document.to_iiif(uuid_mgr, IIIF_BASE_URL), f, indent=2, ensure_ascii=False)

collection_manifest_uid = uuid_mgr._generate_uuid(f"collection_{DS_SLUG}")
collection = Collection(
    id=collection_manifest_uid,
    label=MultiLingualValue({"en": ["Figures of facades and panoramas extracted from cloudpoints of venetian buildings"]}),
    items=list(documents_2d.values()),
)
with open(f"iiif/collections/{collection_manifest_uid}.json", "w", encoding="utf-8") as f:
    json.dump(collection.to_iiif(IIIF_BASE_URL), f, indent=2, ensure_ascii=False)


# 5. IIIF manifests for 3D LAS models
documents_3d: dict[str, Document] = {}
df_of_hr["3d_filename"] = df_of_hr["metadata"].apply(lambda value: f"edifici_{value['EDIFI_ID']}.las")
for _, row in tqdm(df_of_hr.iterrows(), total=len(df_of_hr), desc="3D IIIF manifests"):
    metadata = row["metadata"]
    label = f"{metadata['aulic_name']}, {metadata['EDIFI_ID']} - {metadata['CIVICI']}"
    filename = row["3d_filename"]
    manifest_uuid = uuid_mgr._generate_uuid(filename)
    scene_id = uuid_mgr._generate_uuid(manifest_uuid + "/scene/1")

    document = Document(
        id=manifest_uuid,
        label=MultiLingualValue({"en": [label]}),
        items=[
            Model(
                id=scene_id,
                label=MultiLingualValue({"en": [label]}),
                format="application/vnd.las",
                object_ref=f"http://timeatlas.eu/assets/las/{filename}",
                annotations=[
                    Annotation(
                        id=uuid_mgr._generate_uuid(f"{scene_id}_{row['id']}"),
                        lang="en",
                        value=label,
                        hr_id=row["id"],
                    )
                ],
            )
        ],
    )
    documents_3d[manifest_uuid] = document
    with open(f"iiif/manifests/{manifest_uuid}.json", "w", encoding="utf-8") as f:
        json.dump(document.to_iiif(uuid_mgr, IIIF_BASE_URL, presentation_version="4"), f, indent=2, ensure_ascii=False)

collection_3d_manifest_uid = uuid_mgr._generate_uuid(f"collection_3d_{DS_SLUG}")
collection_3d = Collection(
    id=collection_3d_manifest_uid,
    label=MultiLingualValue({"en": ["Cloudpoints models in LAS format from all venetian buildings from contemporary data acquisition"]}),
    items=list(documents_3d.values()),
)
with open(f"iiif/collections/{collection_3d_manifest_uid}.json", "w", encoding="utf-8") as f:
    json.dump(collection_3d.to_iiif(IIIF_BASE_URL, with_thumbnails=False), f, indent=2, ensure_ascii=False)


# 6. Dataset object
df.rename(columns={"volume [m3]": "volume"}, inplace=True)
labels_order = list(DATA_CONFIG["DATASET_CONFIGURATION"]["labels"].keys())
dataset = Dataset.constructor_from_dataconfiguration_file_and_dataframe(
    "dataproduction_config_edifici.json",
    df[[column for column in labels_order if column in df.columns]],
    sources=[collection_manifest_uid],
    ds_id=DS_UUID,
)


# 7. Validate and save
referenced_geometry_ids = set(df["geometry_uuid"].dropna())
map_collection = RDECollection.read_rde_from_files(MAP_FOLDER)
referenced_geometries = [
    rde
    for rde in map_collection.rdes
    if isinstance(rde, Geometry) and rde.id in referenced_geometry_ids
]

full_collection = RDECollection(historical_records + observations + [dataset] + referenced_geometries)
full_collection.validate_data()
print("Validation passed.")

full_collection.save_rde_to_files(".", overwrite=True, rde_types=[HistoricalRecord, Observation, Dataset])
print(f"Saved {len(historical_records)} HRs, {len(observations)} observations, and 1 dataset.")
